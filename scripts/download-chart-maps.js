#!/usr/bin/env node
/**
 * 下载 Chart 技能内置地图 GeoJSON（构建前 / 首次 clone 后执行）。
 *
 * 数据源：
 *   - 中国省级 + 各省市级 + 各地级市下辖区县：阿里云 DataV GeoAtlas (areas_v3/bound)
 *   - 世界：Apache ECharts 官方示例 geo 资源（英文国名）
 *
 * 输出：
 *   resources/chart-maps/{world.json, china.json, provinces/*.json, cities/*.json, manifest.json}
 *   shared/chart-maps/cities-index.ts（地级市索引，供 region 解析）
 */
const fs = require('fs')
const path = require('path')
const https = require('https')

const ROOT = path.join(__dirname, '..')
const OUT_DIR = path.join(ROOT, 'resources/chart-maps')
const PROV_DIR = path.join(OUT_DIR, 'provinces')
const CITY_DIR = path.join(OUT_DIR, 'cities')
const CITIES_INDEX_TS = path.join(ROOT, 'shared/chart-maps/cities-index.ts')

const DATAV_BASE = 'https://geo.datav.aliyun.com/areas_v3/bound'
const WORLD_URL = 'https://echarts.apache.org/examples/data/asset/geo/world.json'

const PROVINCE_ADCODES = [
  '110000', '120000', '130000', '140000', '150000',
  '210000', '220000', '230000', '310000', '320000',
  '330000', '340000', '350000', '360000', '370000',
  '410000', '420000', '430000', '440000', '450000',
  '460000', '500000', '510000', '520000', '530000',
  '540000', '610000', '620000', '630000', '640000',
  '650000', '710000', '810000', '820000'
]

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, res => {
      if (res.statusCode === 301 || res.statusCode === 302) {
        return fetchJson(res.headers.location).then(resolve, reject)
      }
      if (res.statusCode !== 200) {
        reject(new Error(`HTTP ${res.statusCode} for ${url}`))
        res.resume()
        return
      }
      const chunks = []
      res.on('data', c => chunks.push(c))
      res.on('end', () => {
        try {
          resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')))
        } catch (e) {
          reject(new Error(`Invalid JSON from ${url}: ${e.message}`))
        }
      })
    })
    req.on('error', reject)
    req.setTimeout(120_000, () => {
      req.destroy(new Error(`Timeout: ${url}`))
    })
  })
}

function writeJson(filePath, data) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, JSON.stringify(data))
}

function cityNamesFromFeature(name) {
  const trimmed = String(name).trim()
  const short = trimmed.replace(/(特别行政区|自治州|地区|盟|市)$/, '')
  const names = short && short !== trimmed ? [short, trimmed] : [trimmed]
  return [...new Set(names)]
}

/** 从已下载的省级 GeoJSON 提取地级市 adcode（level=city） */
function collectPrefectureCities() {
  const cities = new Map()
  for (const provAdcode of PROVINCE_ADCODES) {
    const file = path.join(PROV_DIR, `${provAdcode}.json`)
    if (!fs.existsSync(file)) continue
    const geo = JSON.parse(fs.readFileSync(file, 'utf8'))
    for (const feat of geo.features || []) {
      const props = feat.properties
      if (!props || props.level !== 'city') continue
      const adcode = String(props.adcode).padStart(6, '0')
      cities.set(adcode, {
        adcode,
        names: cityNamesFromFeature(props.name),
        label: props.name,
        provinceAdcode: provAdcode
      })
    }
  }
  return cities
}

function writeCitiesIndexTs(cities, successfulAdcodes) {
  const okSet = new Set(successfulAdcodes)
  const sorted = [...cities.values()]
    .filter(c => okSet.has(c.adcode))
    .sort((a, b) => a.adcode.localeCompare(b.adcode))
  const lines = sorted.map(c => {
    const namesJson = JSON.stringify(c.names)
    return `  { adcode: '${c.adcode}', names: ${namesJson} }`
  })
  const content = `/**
 * AUTO-GENERATED by scripts/download-chart-maps.js — do not edit manually.
 * 中国地级市索引（363 个左右），用于 region 名称 / adcode 解析。
 */
export const CHINA_CITIES: ReadonlyArray<{ adcode: string; names: readonly string[] }> = [
${lines.join(',\n')}
]
`
  fs.mkdirSync(path.dirname(CITIES_INDEX_TS), { recursive: true })
  fs.writeFileSync(CITIES_INDEX_TS, content)
}

async function downloadCities(cities) {
  fs.mkdirSync(CITY_DIR, { recursive: true })
  let ok = 0
  let fail = 0
  const entries = [...cities.values()].sort((a, b) => a.adcode.localeCompare(b.adcode))
  for (const city of entries) {
    const dest = path.join(CITY_DIR, `${city.adcode}.json`)
    process.stdout.write(`  cities/${city.adcode}.json (${city.label}) ... `)
    try {
      const geo = await fetchJson(`${DATAV_BASE}/${city.adcode}_full.json`)
      writeJson(dest, geo)
      ok++
      console.log('ok')
    } catch (err) {
      fail++
      console.log(`FAIL (${err.message})`)
    }
  }
  return { ok, fail, adcodes: entries.map(c => c.adcode) }
}

async function main() {
  const citiesOnly = process.argv.includes('--cities-only')
  let provOk = 0
  let provFail = 0
  console.log(citiesOnly ? 'Updating city district maps only...' : 'Downloading chart map GeoJSON...')
  if (!citiesOnly) {
    fs.mkdirSync(PROV_DIR, { recursive: true })

    console.log('  world.json ...')
    const world = await fetchJson(WORLD_URL)
    writeJson(path.join(OUT_DIR, 'world.json'), world)

    console.log('  china.json (100000_full) ...')
    const china = await fetchJson(`${DATAV_BASE}/100000_full.json`)
    writeJson(path.join(OUT_DIR, 'china.json'), china)

    for (const adcode of PROVINCE_ADCODES) {
      const dest = path.join(PROV_DIR, `${adcode}.json`)
      process.stdout.write(`  provinces/${adcode}.json ... `)
      try {
        const geo = await fetchJson(`${DATAV_BASE}/${adcode}_full.json`)
        writeJson(dest, geo)
        provOk++
        console.log('ok')
      } catch (err) {
        provFail++
        console.log(`FAIL (${err.message})`)
      }
    }
    console.log(`Provinces: ${provOk} ok, ${provFail} failed`)
  }

  console.log('')
  console.log('Scanning prefecture cities from province maps...')
  const cities = collectPrefectureCities()
  console.log(`  Found ${cities.size} prefecture-level cities`)

  console.log('Downloading city district maps...')
  const { ok: cityOk, fail: cityFail, adcodes: cityAdcodes } = await downloadCities(cities)

  const successfulCityAdcodes = cityAdcodes.filter(adcode =>
    fs.existsSync(path.join(CITY_DIR, `${adcode}.json`))
  )
  writeCitiesIndexTs(cities, successfulCityAdcodes)
  console.log(`  Wrote ${CITIES_INDEX_TS} (${successfulCityAdcodes.length} cities)`)

  const manifest = {
    version: 2,
    sources: {
      china: 'Aliyun DataV GeoAtlas areas_v3/bound/100000_full.json',
      provinces: 'Aliyun DataV GeoAtlas areas_v3/bound/{adcode}_full.json',
      cities: 'Aliyun DataV GeoAtlas areas_v3/bound/{cityAdcode}_full.json',
      world: 'Apache ECharts examples/data/asset/geo/world.json'
    },
    provinceAdcodes: PROVINCE_ADCODES,
    cityAdcodes: successfulCityAdcodes,
    downloadedAt: new Date().toISOString()
  }
  writeJson(path.join(OUT_DIR, 'manifest.json'), manifest)

  console.log('')
  console.log(`Done: ${cityOk} city district maps (${cityFail} failed)${citiesOnly ? '' : ` + world + china + ${provOk} provinces (${provFail} failed)`}`)
  if (!citiesOnly && provFail > 0) {
    console.warn('Some province maps failed; national china.json still includes all provinces.')
  }
  if (cityFail > 0) {
    console.warn('Some city district maps failed; check DataV availability for those adcodes.')
  }
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
