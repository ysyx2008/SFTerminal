#!/usr/bin/env node
/**
 * 开发态安装 sailfish → ~/.local/bin/sailfish（不启 Electron）
 * 装机用户请用 App「设置 → 数据管理 → 安装 sailfish 命令」
 */
'use strict'

const fs = require('fs')
const os = require('os')
const path = require('path')

const repoRoot = path.resolve(__dirname, '..')
const mainJs = path.join(repoRoot, 'electron', 'cli', 'main.js')
const binDir = path.join(os.homedir(), '.local', 'bin')
const shimPath = path.join(binDir, 'sailfish')

if (!fs.existsSync(mainJs)) {
  console.error('CLI entry not found:', mainJs)
  process.exit(1)
}

fs.mkdirSync(binDir, { recursive: true })
const body = `#!/bin/bash
# SailFish CLI shim (development) — generated by scripts/install-sailfish-cli-dev.js
set -euo pipefail
NODE="\${NODE_BINARY:-node}"
MAIN=${JSON.stringify(mainJs)}
export SFT_CLI_MODE=1
cd ${JSON.stringify(repoRoot)}
exec "$NODE" "$MAIN" "$@"
`
fs.writeFileSync(shimPath, body, { mode: 0o755 })
try { fs.chmodSync(shimPath, 0o755) } catch { /* ignore */ }

console.log('Installed:', shimPath)
const pathEnv = process.env.PATH || ''
const onPath = pathEnv.split(path.delimiter).some(p => path.resolve(p) === path.resolve(binDir))
if (!onPath) {
  console.log(`\nAdd to PATH, then reopen the terminal:\n  export PATH="${binDir}:$PATH"`)
}
console.log('\nTry: sailfish --help')
